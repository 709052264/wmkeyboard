#!/usr/bin/env python3
"""Write an emoji order preset (app/src/main/assets/emoji/order/<id>.txt).

A preset arranges the emoji panel the way another keyboard does (see
EmojiOrderPreset.kt). The input is that keyboard's tabs, already read off it
and mapped onto our catalog category ids, one line per tab in tab order:

    <category id> <TAB> <emoji> <emoji> ...

Each emoji may be in any form the other keyboard uses — with or without
U+FE0F, skin-toned, a gender variant — and is folded onto the catalog's base
id; the grid draws bases, and variants live in the long-press. Emoji our
catalog lacks are dropped, and a repeat keeps its first place.

A tab whose folded order is exactly the catalog's own order for that category
is written as a bare id, which the app stores as no order at all.

--grid writes that keyboard's grid as an `@grid` line of key=value pairs:
columns (0 = fit by cell), row (row height, dp), cell (dp), emoji (glyph
size) and continuous (true when every tab is one long list).

Usage:
  python3 tools/emoji/order_preset.py --source tabs.tsv --name "Gboard 15.2" \
      --out app/src/main/assets/emoji/order/gboard.txt \
      [--grid "columns=8 row=51 emoji=34 continuous=true"] \
      [--catalog app/src/main/assets/emoji/catalog.tsv]
"""

from __future__ import annotations

import argparse
from pathlib import Path

TONES = set(range(0x1F3FB, 0x1F400))
VS16 = 0xFE0F


def fold(s: str) -> str:
    return "".join(c for c in s if ord(c) != VS16 and ord(c) not in TONES)


def load_catalog(path: Path):
    """Base ids in catalog order, their category, and every folded form -> base."""
    order: list[str] = []
    category: dict[str, str] = {}
    to_base: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        # Only the header is a comment: "#️⃣" is a row of its own.
        if not line or line.startswith("# emoji\t"):
            continue
        cols = line.split("\t")
        emoji, cat = cols[0], cols[1]
        parent = cols[4] if len(cols) > 4 else ""
        base = parent or emoji
        if not parent and emoji not in category:
            order.append(emoji)
            category[emoji] = cat
        to_base.setdefault(fold(emoji), base)
    # A variant row may name a parent that folds differently; make sure the
    # base's own folded form wins over a variant that collides with it.
    for base in order:
        to_base[fold(base)] = base
    return order, category, to_base


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--name", required=True, help="keyboard and version, for the header")
    ap.add_argument("--grid", default="", help="key=value pairs for the @grid line")
    ap.add_argument("--catalog", type=Path, default=Path("app/src/main/assets/emoji/catalog.tsv"))
    args = ap.parse_args()

    order, category, to_base = load_catalog(args.catalog)
    by_category: dict[str, list[str]] = {}
    for base in order:
        by_category.setdefault(category[base], []).append(base)

    seen: set[str] = set()
    lines: list[str] = []
    unknown: list[str] = []
    moved = 0
    for raw in args.source.read_text(encoding="utf-8").splitlines():
        if not raw.strip() or raw.startswith("#"):
            continue
        tab, _, rest = raw.partition("\t")
        tab = tab.strip()
        if tab not in by_category:
            raise SystemExit(f"unknown catalog category {tab!r}")
        ids: list[str] = []
        for token in rest.split():
            base = to_base.get(fold(token))
            if base is None:
                unknown.append(token)
                continue
            if base in seen:
                continue
            seen.add(base)
            ids.append(base)
            if category[base] != tab:
                moved += 1
        lines.append(tab if ids == by_category[tab] else tab + " " + " ".join(ids))

    missing = [b for b in order if b not in seen]
    header = [
        f"# Emoji tabs as {args.name} arranges them. One line per tab, in tab",
        "# order: a catalog category id, then its emoji in that keyboard's order.",
        "# A category with no line is hidden; a bare id keeps catalog order.",
        "# Generated by tools/emoji/order_preset.py; see EmojiOrderPreset.kt.",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    grid = ["@grid " + args.grid.strip()] if args.grid.strip() else []
    args.out.write_text("\n".join(header + grid + lines) + "\n", encoding="utf-8")
    print(f"{args.out}: {len(lines)} tabs, {len(seen)} emoji placed, {moved} moved across categories")
    print(f"  {len(unknown)} not in our catalog: {' '.join(unknown[:40])}")
    print(f"  {len(missing)} of ours the source lacks: {' '.join(missing[:60])}")


if __name__ == "__main__":
    main()
