package com.wasimaster.wmkeyboard.core.script

/**
 * Languages added for the sentence corpora in wmkeyboard-data rather than for a
 * keyboard someone published: Tatoeba's sentences (and a few Wikipedia and
 * Glot500 word lists the repository already carried) for languages neither
 * [LanguageRegistry]'s hand-written list nor [KeymanLanguages] offered.
 *
 * Each has a QWERTY-shaped grid built from its script's usual template
 * (Karachay-Balkar's for Cyrillic, the all-letters Arabic one, Hebrew SI-1452, Awadhi's
 * InScript, Georgian standard, Kedmanee), with every letter the corpus uses
 * and the template lacks put on the long press of the key it is a variant of,
 * plus its script's T9 pad. Some have a word list; the ones whose corpus is a
 * few dozen sentences have the layout alone.
 *
 * Its own file, and its entries split across several functions, for the
 * reason [KeymanLanguages] gives: one `listOf` initializer of a few hundred
 * entries runs into the JVM's 64 KB method limit.
 */
