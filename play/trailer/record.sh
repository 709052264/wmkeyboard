#!/usr/bin/env bash
# Trailer footage capture rig. Records 1080x2400 clips via scrcpy (the
# on-device `screenrecord` binary is blocked on ColorOS — "Permission denied"
# for any output path), trims/normalizes into public/clips/, and regenerates
# src/clips.ts so scenes pick them up.
#
# Usage:
#   ./record.sh start <name> [seconds]   # record footage/<name>.mp4 (default 8s)
#   ./record.sh trim <name> <ss> <to>    # ffmpeg trim footage -> public/clips
#   ./record.sh manifest                 # regenerate src/clips.ts
#   ./record.sh demo on|off              # SystemUI demo mode (clean statusbar)
#   ./record.sh shorts trim <name> <ss> <to>  # footage -> public/shorts/clips
#   ./record.sh shorts manifest|vo|render|sheet|thumb  # see the shorts) block
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p footage public/clips

case "${1:-}" in
  start)
    NAME="${2:?name}"; SECS="${3:-8}"
    scrcpy --no-playback --no-audio --record="footage/$NAME.mp4" --time-limit="$SECS"
    ;;
  trim)
    NAME="${2:?name}"; SS="${3:-0}"; TO="${4:-}"
    TOARG=(); [ -n "$TO" ] && TOARG=(-to "$TO")
    # scrcpy output is variable-frame-rate; force CFR 30 for Remotion.
    ffmpeg -y -ss "$SS" "${TOARG[@]}" -i "footage/$NAME.mp4" \
      -c:v libx264 -preset slow -crf 20 -pix_fmt yuv420p -r 30 -fps_mode cfr \
      -an -movflags +faststart "public/clips/$NAME.mp4"
    "$0" manifest
    ;;
  manifest)
    {
      echo "// Regenerated by record.sh (gen_manifest) — lists files present in public/clips."
      echo "// Scenes fall back to a placeholder panel for clips not yet captured."
      echo "export const AVAILABLE_CLIPS: string[] = ["
      for f in public/clips/*.mp4; do
        [ -e "$f" ] && echo "  \"$(basename "$f")\","
      done
      echo "];"
      echo ""
      echo "// Set to a filename in public/ (e.g. \"music.mp3\") to mix a soundtrack."
      if [ -e public/music.mp3 ]; then
        echo "export const MUSIC: string | null = \"music.mp3\";"
      else
        echo "export const MUSIC: string | null = null;"
      fi
    } > src/clips.ts
    echo "wrote src/clips.ts"
    ;;
  shorts)
    # Promo shorts live beside the trailer but never touch src/clips.ts.
    mkdir -p public/shorts/clips public/shorts/vo out/shorts
    case "${2:-}" in
      trim)
        NAME="${3:?name}"; SS="${4:-0}"; TO="${5:-}"
        TOARG=(); [ -n "$TO" ] && TOARG=(-to "$TO")
        # scrcpy takes are .mkv since batch 2 (an interrupted .mp4 has no moov atom).
        SRC="footage/$NAME.mp4"; [ -e "$SRC" ] || SRC="footage/$NAME.mkv"
        ffmpeg -y -ss "$SS" "${TOARG[@]}" -i "$SRC" \
          -c:v libx264 -preset slow -crf 20 -pix_fmt yuv420p -r 30 -fps_mode cfr \
          -an -movflags +faststart "public/shorts/clips/$NAME.mp4"
        "$0" shorts manifest
        ;;
      manifest)
        # Clip lengths for both clip folders; ScreenCard loops short clips.
        {
          echo "// Regenerated by record.sh (shorts manifest) — clip lengths in seconds for"
          echo "// every file in public/clips and public/shorts/clips, keyed by public path."
          echo "export const SHORT_CLIPS: Record<string, number> = {"
          for f in public/clips/*.mp4 public/shorts/clips/*.mp4; do
            [ -e "$f" ] || continue
            D=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$f")
            printf '  "%s": %.3f,\n' "${f#public/}" "$D"
          done
          echo "};"
        } > src/shorts/clips.ts
        echo "wrote src/shorts/clips.ts"
        ;;
      vo)
        # Placeholder VO from macOS `say`, one phrase per line of TEXT, plus a
        # Caption[] word-timestamp JSON (word times spread by length inside
        # each phrase). Replace both with the real take + its transcript.
        ID="${3:?id}"; TEXT="${4:?text, one phrase per line}"; VOICE="${WM_VOICE:-Samantha}"
        TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
        GAP=0.12; i=0; : > "$TMP/list.txt"; : > "$TMP/phrases.tsv"
        while IFS= read -r LINE; do
          [ -n "$LINE" ] || continue
          say -v "$VOICE" -r 190 -o "$TMP/p$i.aiff" "$LINE"
          # trim leading/trailing silence so phrase timing is honest
          ffmpeg -v error -y -i "$TMP/p$i.aiff" -af \
            "silenceremove=start_periods=1:start_threshold=-50dB,areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse,apad=pad_dur=$GAP" \
            -ar 48000 -ac 2 "$TMP/p$i.wav"
          D=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$TMP/p$i.wav")
          printf '%s\t%s\n' "$D" "$LINE" >> "$TMP/phrases.tsv"
          echo "file '$TMP/p$i.wav'" >> "$TMP/list.txt"
          i=$((i + 1))
        done <<< "$TEXT"
        ffmpeg -v error -y -f concat -safe 0 -i "$TMP/list.txt" -c:a pcm_s16le "public/shorts/vo/$ID.wav"
        GAP="$GAP" node -e '
          const fs = require("fs");
          const gap = Number(process.env.GAP) * 1000;
          let t = 0; const out = [];
          for (const row of fs.readFileSync(process.argv[1], "utf8").trim().split("\n")) {
            const [d, line] = row.split("\t");
            const speak = Number(d) * 1000 - gap;
            const words = line.split(/\s+/).filter(Boolean);
            const weight = words.reduce((n, w) => n + w.length + 2, 0);
            let at = t;
            words.forEach((w, k) => {
              const len = (speak * (w.length + 2)) / weight;
              out.push({ text: (out.length ? " " : "") + w, startMs: Math.round(at), endMs: Math.round(at + len), timestampMs: Math.round(at + len / 2), confidence: null });
              at += len;
            });
            t += Number(d) * 1000;
          }
          fs.writeFileSync(process.argv[2], JSON.stringify(out, null, 1) + "\n");
          console.log(`wrote ${process.argv[2]} (${out.length} words, ${(t / 1000).toFixed(2)} s)`);
        ' "$TMP/phrases.tsv" "public/shorts/vo/$ID.json"
        ;;
      render)
        # Both masters (full = with bed, stem = VO + SFX) for ShortNN.
        COMP="${3:?ShortNN}"; ID="${4:?id}"
        npx remotion render "$COMP" "out/shorts/$ID-full.mp4"
        npx remotion render "$COMP" "out/shorts/$ID-stem.mp4" --props='{"bed":false}'
        ;;
      sheet)
        # Safe-zone contact sheet: overlay on, one tile every 1.5 s.
        COMP="${3:?ShortNN}"; ID="${4:?id}"
        npx remotion render "$COMP" "out/shorts/$ID-safezone.mp4" --props='{"safeZone":true}' --scale=0.5 --muted
        ffmpeg -v error -y -i "out/shorts/$ID-safezone.mp4" \
          -vf "fps=2/3,scale=270:-1,tile=6x2:padding=8:margin=8:color=0x0A0D14" \
          -frames:v 1 "out/shorts/$ID-sheet.png"
        rm "out/shorts/$ID-safezone.mp4"
        echo "wrote out/shorts/$ID-sheet.png"
        ;;
      thumb)
        # Cover stills: <comp>-thumb (1080x1920) and <comp>-thumb-yt (1280x720).
        # Optional look overrides spec.look for a quick comparison.
        COMP="${3:?DayNN}"; LOOK="${4:-}"
        PROPS=(); SUFFIX=""
        [ -n "$LOOK" ] && PROPS=(--props="{\"look\":\"$LOOK\"}") && SUFFIX="-$LOOK"
        mkdir -p out/shorts/thumbs
        npx remotion still "$COMP-thumb" "out/shorts/thumbs/$COMP$SUFFIX.png" ${PROPS[@]+"${PROPS[@]}"}
        npx remotion still "$COMP-thumb-yt" "out/shorts/thumbs/$COMP$SUFFIX-yt.png" ${PROPS[@]+"${PROPS[@]}"}
        ;;
      *)
        echo "usage: record.sh shorts trim|manifest|vo|render|sheet|thumb" >&2; exit 1
        ;;
    esac
    ;;
  demo)
    if [ "${2:-on}" = "on" ]; then
      adb shell settings put global sysui_demo_allowed 1
      adb shell am broadcast -a com.android.systemui.demo -e command enter
      adb shell am broadcast -a com.android.systemui.demo -e command clock -e hhmm 0100
      adb shell am broadcast -a com.android.systemui.demo -e command battery -e level 100 -e plugged false
      adb shell am broadcast -a com.android.systemui.demo -e command network -e wifi show -e level 4
      adb shell am broadcast -a com.android.systemui.demo -e command notifications -e visible false
    else
      adb shell am broadcast -a com.android.systemui.demo -e command exit
    fi
    ;;
  *)
    echo "usage: record.sh start|trim|manifest|shorts|demo" >&2; exit 1
    ;;
esac
