import org.gradle.api.DefaultTask
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Writes the R8 keep rules of the `wmkeyboard.native-gates` convention: one
 * `-keep class … { *; }` per JNI class native/gates.json names (`keep`), the
 * classes whose library binds by the mangled Java name
 * (`Java_com_wasimaster_…_HarperNative_*`), so neither the class name nor its
 * external methods may be renamed or stripped. The general
 * `-keepclasseswithmembernames … native <methods>` rule stays in
 * app/proguard-rules.pro.
 */
abstract class NativeKeepsTask : DefaultTask() {

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val table: RegularFileProperty

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun write() {
        val gates = NativeGates.read(table.get().asFile)
        val text = buildString {
            appendLine("# Generated by the wmkeyboard.native-gates convention from native/gates.json.")
            appendLine("# Each library below binds by the mangled Java name of its JNI class.")
            for ((gate, library) in gates.ownLibraries) {
                for (cls in library.keep) {
                    appendLine()
                    appendLine("# ${library.name}, gate ${gate.id}")
                    appendLine("-keep class $cls { *; }")
                }
            }
        }
        outputFile.get().asFile.apply { parentFile.mkdirs() }.writeText(text)
    }
}
