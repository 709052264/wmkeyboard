// JNI bridge between com.wasimaster.wmkeyboard.core.localllm.LlamaNative and
// llama.cpp. See README.md for the contract; LlamaCppRuntime is the only
// caller.
//
// A model handle owns the weights (mmapped) and the chat templates read from
// the GGUF. A session handle owns one llama_context (the KV cache), one
// sampler chain and the tokens the cache holds, so a new prompt that starts
// with the same tokens (the next turn of a chat) only decodes what is new.
// Text crosses as UTF-8 byte arrays, never NewStringUTF: a token can end in
// the middle of a character, and JNI's modified UTF-8 has no room for
// four-byte characters. One thread per session at a time, except
// nativeAbort, which any thread may call.

