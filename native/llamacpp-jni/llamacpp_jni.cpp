// JNI bridge between com.wasimaster.wmkeyboard.core.localllm.LlamaNative and
// llama.cpp. See README.md for the contract; LlamaCppRuntime is the only
// caller.
//
// A model handle owns the weights (mmapped, or uploaded to the GPU) and the
// chat templates read from the GGUF. A session handle owns one llama_context
// (the KV cache), one sampler chain and the tokens the cache holds, so a new
// prompt that starts with the same tokens (the next turn of a chat) only
// decodes what is new. A vision handle owns a vision model's projector (its
// mmproj file, through libmtmd), which turns a picture into the embeddings a
// prompt carries in place of tokens. Text crosses as UTF-8 byte arrays, never
// NewStringUTF: a token can end in the middle of a character, and JNI's
// modified UTF-8 has no room for four-byte characters. One thread per session
// at a time, except nativeAbort, which any thread may call.

