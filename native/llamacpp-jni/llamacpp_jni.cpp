namespace {

std::once_flag g_backend_once;

void log_callback(ggml_log_level level, const char * text, void *) {
    // Warnings and errors only: llama.cpp is chatty at info level, and the
    // keyboard's log is shared with everything else it does.
    if (level != GGML_LOG_LEVEL_WARN && level != GGML_LOG_LEVEL_ERROR) return;
#ifdef __ANDROID__
    __android_log_write(level == GGML_LOG_LEVEL_ERROR ? ANDROID_LOG_ERROR : ANDROID_LOG_WARN, "WMLlama", text);
#else
    fputs(text, stderr);
#endif
}

void ensure_backend() {
    std::call_once(g_backend_once, [] {
        llama_log_set(log_callback, nullptr);
        // The chat-template code logs through llama.cpp's common log, which
        // starts a thread of its own on the first line. Errors only.
        common_log_set_verbosity_thold(LOG_LEVEL_ERROR);
        llama_backend_init();
    });
}

struct Model {
    llama_model * model = nullptr;
    common_chat_templates_ptr templates;
};

// Why the last nativeNext returned null.
enum StopReason : jint { STOP_END = 0, STOP_CONTEXT_FULL = 1, STOP_ABORTED = 2, STOP_ERROR = 3 };

// nativePrompt* failures, returned as negative token counts.
enum PromptError : jint { PROMPT_TOO_LONG = -1, PROMPT_ABORTED = -2, PROMPT_DECODE_FAILED = -3, PROMPT_TEMPLATE_FAILED = -4 };

struct Session {
    Model * model = nullptr;
    llama_context * ctx = nullptr;
    llama_sampler * sampler = nullptr;
    std::vector<llama_token> cached;  // the tokens the KV cache holds, in order
    std::atomic<bool> abort{false};
    std::string pending;               // generated bytes that end mid-character
    bool finished = false;             // nativeNext has seen the end; next call returns null
    jint stop_reason = STOP_END;
    int reused = 0;                    // tokens the last prompt kept from the cache
};

bool abort_callback(void * data) {
    return static_cast<Session *>(data)->abort.load(std::memory_order_relaxed);
}

std::string bytes_to_string(JNIEnv * env, jbyteArray bytes) {
    if (bytes == nullptr) return {};
    const jsize n = env->GetArrayLength(bytes);
    std::string out(static_cast<size_t>(n), '\0');
    if (n > 0) env->GetByteArrayRegion(bytes, 0, n, reinterpret_cast<jbyte *>(&out[0]));
    return out;
}

jbyteArray string_to_bytes(JNIEnv * env, const std::string & s) {
    jbyteArray out = env->NewByteArray(static_cast<jsize>(s.size()));
    if (out != nullptr && !s.empty()) {
        env->SetByteArrayRegion(out, 0, static_cast<jsize>(s.size()), reinterpret_cast<const jbyte *>(s.data()));
    }
    return out;
}

// Length of the longest prefix of s that does not end inside a UTF-8
// sequence. Malformed bytes count as complete: the Kotlin side decodes them
// to U+FFFD rather than waiting for a continuation that never comes.
size_t complete_utf8_length(const std::string & s) {
    const size_t n = s.size();
    // Walk back over at most three continuation bytes to the lead byte.
    size_t i = n;
    int continuation = 0;
    while (i > 0 && continuation < 3 && (static_cast<unsigned char>(s[i - 1]) & 0xC0) == 0x80) {
        --i;
        ++continuation;
    }
    if (i == 0) return n;
    const unsigned char lead = static_cast<unsigned char>(s[i - 1]);
    size_t need;
    if (lead < 0x80) return n;
    else if ((lead & 0xE0) == 0xC0) need = 2;
    else if ((lead & 0xF0) == 0xE0) need = 3;
    else if ((lead & 0xF8) == 0xF0) need = 4;
    else return n;
    const size_t have = static_cast<size_t>(continuation) + 1;
    return have < need ? i - 1 : n;
}

std::vector<llama_token> tokenize(const llama_vocab * vocab, const std::string & text, bool add_special, bool parse_special) {
    if (text.empty() && !add_special) return {};
    int32_t n = -llama_tokenize(vocab, text.data(), static_cast<int32_t>(text.size()), nullptr, 0, add_special, parse_special);
    if (n <= 0) {
        // Positive means it fitted in zero tokens: nothing to add.
        return {};
    }
    std::vector<llama_token> tokens(static_cast<size_t>(n));
    const int32_t got = llama_tokenize(vocab, text.data(), static_cast<int32_t>(text.size()), tokens.data(), n, add_special, parse_special);
    if (got < 0) return {};
    tokens.resize(static_cast<size_t>(got));
    return tokens;
}

std::string token_piece(const llama_vocab * vocab, llama_token token) {
    char buf[256];
    int32_t n = llama_token_to_piece(vocab, token, buf, sizeof(buf), 0, false);
    if (n >= 0) return std::string(buf, static_cast<size_t>(n));
    std::string big(static_cast<size_t>(-n), '\0');
    n = llama_token_to_piece(vocab, token, &big[0], static_cast<int32_t>(big.size()), 0, false);
    return n >= 0 ? big.substr(0, static_cast<size_t>(n)) : std::string();
}

// Decodes tokens[from..] after the cache, in batches; logits for the last
// one only. Returns 0, or a PromptError.
jint decode_tail(Session * s, const std::vector<llama_token> & tokens, size_t from) {
    const size_t n_batch = llama_n_batch(s->ctx);
    for (size_t i = from; i < tokens.size(); i += n_batch) {
        if (s->abort.load()) return PROMPT_ABORTED;
        const size_t count = std::min(n_batch, tokens.size() - i);
        llama_batch batch = llama_batch_get_one(const_cast<llama_token *>(tokens.data() + i), static_cast<int32_t>(count));
        const int32_t rc = llama_decode(s->ctx, batch);
        if (rc != 0) {
            // What did get in is in the cache now; drop it so the cache and
            // `cached` agree again.
            llama_memory_seq_rm(llama_get_memory(s->ctx), 0, static_cast<llama_pos>(i), -1);
            s->cached.assign(tokens.begin(), tokens.begin() + static_cast<long>(i));
            return rc == 2 ? PROMPT_ABORTED : PROMPT_DECODE_FAILED;
        }
        s->cached.insert(s->cached.end(), tokens.begin() + static_cast<long>(i), tokens.begin() + static_cast<long>(i + count));
    }
    return 0;
}

// Makes the cache hold exactly `tokens`, reusing the longest common prefix.
// Returns the token count, or a PromptError.
jint load_prompt(Session * s, const std::vector<llama_token> & tokens) {
    s->abort.store(false);
    s->pending.clear();
    s->finished = false;
    s->stop_reason = STOP_END;
    if (tokens.empty()) return PROMPT_TEMPLATE_FAILED;
    // Room to answer: a prompt that fills the window leaves none.
    const size_t n_ctx = llama_n_ctx(s->ctx);
    if (tokens.size() + 8 > n_ctx) return PROMPT_TOO_LONG;

    size_t keep = 0;
    while (keep < s->cached.size() && keep < tokens.size() && s->cached[keep] == tokens[keep]) ++keep;
    // The last prompt token is always decoded again: its logits are what the
    // first sample reads, and the cache keeps no logits.
    if (keep == tokens.size()) --keep;
    llama_memory_t mem = llama_get_memory(s->ctx);
    if (keep < s->cached.size()) {
        if (!llama_memory_seq_rm(mem, 0, static_cast<llama_pos>(keep), -1)) {
            // Recurrent and some sliding-window caches cannot cut part way.
            llama_memory_clear(mem, true);
            keep = 0;
        }
        s->cached.resize(keep);
    }
    s->reused = static_cast<int>(keep);
    llama_sampler_reset(s->sampler);
    const jint rc = decode_tail(s, tokens, keep);
    return rc < 0 ? rc : static_cast<jint>(tokens.size());
}

llama_sampler * make_sampler(float temperature, int top_k, float top_p, float min_p, uint32_t seed) {
    llama_sampler * chain = llama_sampler_chain_init(llama_sampler_chain_default_params());
    if (temperature <= 0.0f) {
        llama_sampler_chain_add(chain, llama_sampler_init_greedy());
        return chain;
    }
    if (top_k > 0) llama_sampler_chain_add(chain, llama_sampler_init_top_k(top_k));
    if (top_p > 0.0f && top_p < 1.0f) llama_sampler_chain_add(chain, llama_sampler_init_top_p(top_p, 1));
    if (min_p > 0.0f) llama_sampler_chain_add(chain, llama_sampler_init_min_p(min_p, 1));
    llama_sampler_chain_add(chain, llama_sampler_init_temp(temperature));
    llama_sampler_chain_add(chain, llama_sampler_init_dist(seed));
    return chain;
}

Model * as_model(jlong h) { return reinterpret_cast<Model *>(h); }
Session * as_session(jlong h) { return reinterpret_cast<Session *>(h); }

}  // namespace

