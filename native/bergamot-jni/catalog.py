#!/usr/bin/env python3
"""Writes BergamotCatalog.kt: the translation models Firefox for Android
release would pick today, pinned by SHA-256.

Reads Mozilla's public Remote Settings collection `translations-models-v2`
(the one Firefox's TranslationsParent reads) and keeps, for each language
direction, the files of the newest released 3.x model a release build of
Firefox on Android would download:

- versions with a pre-release suffix (3.0a1) are skipped,
- filter expressions other than "" and "env.appinfo.OS == 'Android'" are
  skipped (nightly-only, desktop-only),
- every file of a direction has the version of its `model` record, as
  TranslationsParent#filterByModelVersion insists.

Run it to re-pin, then review the diff:

    native/bergamot-jni/catalog.py [records.json]

With no argument it fetches the records over HTTPS. Nothing else is needed.
"""
import json
import pathlib
import sys
import urllib.request

COLLECTION = ("https://firefox.settings.services.mozilla.com/v1/buckets/main/"
              "collections/translations-models-v2/records")
PREFIX = "main-workspace/translations-models-v2/"
FILTERS = ("", "env.appinfo.OS == 'Android'")
MAJOR = 3
OUT = (pathlib.Path(__file__).resolve().parents[2] / "core/intelligence/src/main/java/"
       "com/wasimaster/wmkeyboard/core/translate/BergamotCatalog.kt")
KINDS = {"model": "MODEL", "lex": "LEX", "vocab": "VOCAB", "srcvocab": "SRC_VOCAB", "trgvocab": "TRG_VOCAB"}


def version(text):
    return tuple(int(part) for part in text.split("."))


def released(record):
    v = record["version"]
    return (v.replace(".", "").isdigit() and version(v)[0] == MAJOR
            and record.get("filter_expression", "").strip() in FILTERS)


def main():
    if len(sys.argv) > 1:
        records = json.load(open(sys.argv[1]))["data"]
    else:
        with urllib.request.urlopen(COLLECTION, timeout=60) as response:
            records = json.load(response)["data"]
    by_pair = {}
    for r in filter(released, records):
        by_pair.setdefault((r["sourceLanguage"], r["targetLanguage"]), []).append(r)
    lines = []
    for (src, trg), rs in sorted(by_pair.items()):
        models = [r for r in rs if r["fileType"] == "model"]
        if not models:
            continue
        model = max(models, key=lambda r: version(r["version"]))
        chosen = {}
        # An Android-only record wins over a general one of the same kind.
        for r in sorted(rs, key=lambda r: r.get("filter_expression", "") == ""):
            if r["version"] == model["version"]:
                chosen.setdefault(r["fileType"], r)
        if "vocab" not in chosen and not ("srcvocab" in chosen and "trgvocab" in chosen):
            continue
        files = []
        for kind in ("model", "lex", "vocab", "srcvocab", "trgvocab"):
            r = chosen.get(kind)
            if r is None:
                continue
            a = r["attachment"]
            assert a["location"].startswith(PREFIX), a["location"]
            files.append(
                f'            f({KINDS[kind]}, "{r["name"]}", "{a["location"][len(PREFIX):]}", '
                f'{a["size"]}, "{a["hash"]}", {r["decompressedSize"]}, "{r["decompressedHash"]}"),')
        lines.append(f'        d("{src}", "{trg}", "{model["version"]}", "{model["architecture"]}",')
        lines.extend(files)
        lines.append("        ),")
    body = "\n".join(lines)
    OUT.write_text(f'''package com.wasimaster.wmkeyboard.core.translate

import com.wasimaster.wmkeyboard.core.translate.BergamotCatalog.Kind.LEX
import com.wasimaster.wmkeyboard.core.translate.BergamotCatalog.Kind.MODEL
import com.wasimaster.wmkeyboard.core.translate.BergamotCatalog.Kind.SRC_VOCAB
import com.wasimaster.wmkeyboard.core.translate.BergamotCatalog.Kind.TRG_VOCAB
import com.wasimaster.wmkeyboard.core.translate.BergamotCatalog.Kind.VOCAB

// Generated by native/bergamot-jni/catalog.py from Mozilla's Remote Settings
// collection translations-models-v2. Re-run it to re-pin; do not edit by hand.

/**
 * The Firefox Translations models the Bergamot engine can download: one
 * entry per language direction, each file pinned by the SHA-256 of what is
 * downloaded (zstd) and of what it unpacks to. Mozilla serves them from its
 * Remote Settings attachment CDN, [BASE_URL] plus [File.path]. The models
 * are Mozilla's, released under the MPL-2.0 with the engine.
 */
object BergamotCatalog {{

    const val BASE_URL = "https://firefox-settings-attachments.cdn.mozilla.net/{PREFIX}"

    enum class Kind {{ MODEL, LEX, VOCAB, SRC_VOCAB, TRG_VOCAB }}

    /**
     * One file. [size] and [sha256] are the download's; [rawSize] and
     * [rawSha256] the unpacked file the engine reads.
     */
    data class File(
        val kind: Kind,
        val name: String,
        val path: String,
        val size: Long,
        val sha256: String,
        val rawSize: Long,
        val rawSha256: String,
    ) {{
        val url: String get() = BASE_URL + path
    }}

    /**
     * One direction, [from] into [to], by Mozilla's language codes. [version]
     * is the model's release, [architecture] its size class (`tiny` is the
     * smallest and fastest, `base-memory` the larger one Firefox prefers).
     */
    data class Direction(
        val from: String,
        val to: String,
        val version: String,
        val architecture: String,
        val files: List<File>,
    ) {{
        val key: String get() = "$from-$to"

        /** What the download costs. */
        val downloadBytes: Long get() = files.sumOf {{ it.size }}

        /** What it takes on the phone once unpacked. */
        val storedBytes: Long get() = files.sumOf {{ it.rawSize }}
    }}

    private fun f(kind: Kind, name: String, path: String, size: Long, sha256: String, rawSize: Long, rawSha256: String) =
        File(kind, name, path, size, sha256, rawSize, rawSha256)

    private fun d(from: String, to: String, version: String, architecture: String, vararg files: File) =
        Direction(from, to, version, architecture, files.toList())

    val directions: List<Direction> = listOf(
{body}
    )
}}
''')
    print(f"{len(lines)} lines, {sum(1 for l in lines if l.lstrip().startswith('d('))} directions -> {OUT}")


if __name__ == "__main__":
    main()
