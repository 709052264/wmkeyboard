#!/usr/bin/env python3
"""Writes core/voice/src/main/assets/speech/mms_tts.tsv: every Meta MMS-TTS
voice the app can download, pinned to one revision of the ONNX conversion on
Hugging Face, with each file's size and SHA-256.

The model sizes and hashes come from the Hub's LFS pointers; tokens.txt is a
plain git file there, so it is fetched and hashed here. Voices whose tokens
file is not one symbol and one id per line (the sherpa-onnx format the app
reads) or whose code is not ASCII are left out.

    python3 native/sherpa-onnx-jni/mms_tts_catalog.py
"""
import concurrent.futures
import hashlib
import json
import os
import urllib.request

REPO = "willwade/mms-tts-multilingual-models-onnx"
REVISION = "4f49fc254f11ddb0e35fbf25b6e48b04463a6779"
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "core", "voice", "src", "main", "assets", "speech", "mms_tts.tsv")


def fetch(url):
    with urllib.request.urlopen(url) as r:
        return r.read()


def tokens_ok(data):
    for line in data.decode("utf-8").split("\n"):
        if not line.strip():
            continue
        symbol, _, ident = line.rpartition(" ")
        if line.startswith("  "):
            symbol = " "
        if len(symbol) != 1 or not ident.isdigit():
            return False
    return True


def main():
    meta = json.loads(fetch(f"https://huggingface.co/api/models/{REPO}/revision/{REVISION}?blobs=true"))
    files = {s["rfilename"]: s for s in meta["siblings"]}
    codes = sorted({k.split("/")[0] for k in files if k.endswith("/model.onnx")})
    codes = [c for c in codes if c.isascii() and f"{c}/tokens.txt" in files]

    def row(code):
        tokens = fetch(f"https://huggingface.co/{REPO}/resolve/{REVISION}/{code}/tokens.txt")
        if not tokens_ok(tokens):
            return None
        model = files[f"{code}/model.onnx"]
        return (code, model["size"], model["lfs"]["sha256"], len(tokens), hashlib.sha256(tokens).hexdigest())

    with concurrent.futures.ThreadPoolExecutor(8) as pool:
        rows = [r for r in pool.map(row, codes) if r]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(f"# Meta MMS-TTS voices (CC-BY-NC-4.0) as ONNX, from huggingface.co/{REPO}\n")
        f.write(f"# at revision {REVISION}. Generated by native/sherpa-onnx-jni/mms_tts_catalog.py.\n")
        f.write("# code\tmodel.onnx bytes\tmodel.onnx sha256\ttokens.txt bytes\ttokens.txt sha256\n")
        for r in rows:
            f.write("\t".join(map(str, r)) + "\n")
    print(f"{len(rows)} voices -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
